// tb_port_interconnect_noop.v
//
// The NO-OP half of issue #250 AC 5's testbench-sensitivity pair.
//
// klayout-tools#1619 finding 9 reports the failure as "unexpectedly
// sensitive to the *testbench*: the identical fixture resolves cleanly with
// a no-op cocotb test ... but deterministically fails once the testbench
// actually drives the DUT and awaits a Timer", and reads the cause as "a
// genuine Icarus-internal race between $sdf_annotate's own intermodpath
// insertion and VPI callback scheduling once the simulator advances past
// time 0". That was established with cocotb; this repo drives plain Verilog
// testbenches through flow/sdf-resim.sh, so the pair is re-run here in
// plain Verilog to test that reading directly.
//
// This half drives NOTHING: every DUT input keeps its initial value and the
// only `initial` block advances a single time unit and finishes. It is
// otherwise identical in structure to tb_port_interconnect_drive.v, so the
// two differ ONLY in whether the DUT is exercised and how far time advances.
//
// Load-bearing structure (do not "simplify"):
//   * `port_interconnect_dut` is instantiated as a NESTED CHILD named `dut`,
//     mirroring sim/tb_logic_tile.v's `logic_tile dut (...)`. Upstream
//     finding 7 / klayout-tools#1056 is a nesting fix, and a flat top-level
//     DUT would silently test a different question.
//   * `$sdf_annotate` is NOT called from here. It rides in a second
//     elaboration root generated by flow/sdf_annotate_shim.py, exactly as
//     flow/sdf-resim.sh leg 2 does.

`default_nettype none
`timescale 1ns/1ps

module tb_port_interconnect_noop;

    reg  [5:0]  in  = 6'b000000;
    reg         clk = 1'b0;
    wire [19:0] out;

    port_interconnect_dut dut (
        .in  (in),
        .clk (clk),
        .out (out)
    );

    initial begin
        $display("TB: tb_port_interconnect_noop -- no stimulus, no clock");
        #1;
        $display("TB: out = %b", out);
        $display("DONE: tb_port_interconnect_noop");
        $finish;
    end

endmodule

`default_nettype wire

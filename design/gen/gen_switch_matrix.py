#!/usr/bin/env python3
"""Generate design/rtl/logic_tile_switch_matrix.v from the FABulous
switch-matrix list.  Do not hand-edit the output.

Usage (from repo root):
  python3 design/gen/gen_switch_matrix.py \
      design/fabulous/Tile/LOGIC4/LOGIC4_switch_matrix.list \
      design/rtl/logic_tile_switch_matrix.v \
      sim/switch_matrix_tb_gen.vh

The third output is a testbench include (instance port hookup to packed
src/snk vectors plus a sink/select/source table) derived from the same list.

Each "sink,source" line adds one source to the sink's mux.  FABulous 2.2.0
does NOT use file order: it orders sinks by the switch-matrix module's output
port declaration order and each sink's sources by its input port declaration
order (verified by design/fabulous/tb_switch_matrix_equiv.v, issue #96), so
this generator applies the same canonical order (see sink_rank/src_rank):
  sinks  : N1BEG0..3, E1BEG0..3, S1BEG0..3, W1BEG0..3, then per BEL A..D
           (I0..I3, SR, EN), then J_SR_BEG0, J_EN_BEG0..3
  sources: N1END0..3, E1END0..3, S1END0..3, W1END0..3, LA_O..LD_O,
           J_SR_END0, J_EN_END0..3
Source index (in that order, within the sink's own source set) == select
value.  A sink with N sources gets ceil(log2 N) config bits (0 for N == 1).
Config bits are packed into one flat `cfg` vector in sink order, LSB first
(cfg[k] == FABulous tile ConfigBits[68+k]).  Select values >= N drive 0
(FABulous leaves them undefined/X).  Jump wires J_*_BEGn feed J_*_ENDn inside the tile (X/Y offset 0).
"""
import re
import sys
from collections import OrderedDict

def parse(path):
    sinks = OrderedDict()
    for line in open(path):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        dst, src = [t.strip() for t in line.split(",")]
        sinks.setdefault(dst, []).append(src)
    return sinks

def _rank(name, groups):
    m = re.match(r"^([A-Z])(\d)(BEG|END)(\d+)$", name)
    if m:  # track wires: direction-major, then index
        return (0, "NESW".index(m.group(1)), int(m.group(4)))
    m = re.match(r"^L([A-D])_(I(\d)|SR|EN|O)$", name)
    if m:  # BEL pins: BEL-major; pin order I0..I3, SR, EN; O after tracks
        pin = m.group(2)
        order = {"SR": 4, "EN": 5, "O": 0}.get(pin, int(pin[1:]) if pin[0] == "I" else 0)
        return (1, "ABCD".index(m.group(1)), order)
    m = re.match(r"^J_(SR|EN)_(BEG|END)(\d+)$", name)
    if m:  # jump wires: SR before EN
        return (2, 0 if m.group(1) == "SR" else 1, int(m.group(3)))
    raise SystemExit("unknown port name in switch-matrix list: " + name)

def sink_rank(n):   # FABulous output-port declaration order
    return _rank(n, None)

def src_rank(n):    # FABulous input-port declaration order
    return _rank(n, None)

def main(lst, out, tbinc):
    sinks = parse(lst)
    sinks = OrderedDict((d, sorted(sl, key=src_rank))
                        for d, sl in sorted(sinks.items(), key=lambda kv: sink_rank(kv[0])))
    srcs = OrderedDict()
    for dl in sinks.values():
        for s in dl:
            srcs.setdefault(s, None)
    jump = re.compile(r"^J_(EN|SR)_(BEG|END)\d+$")
    ports_in = sorted((s for s in srcs if not jump.match(s)), key=src_rank)
    ports_out = [d for d in sinks if not jump.match(d)]
    jumps = sorted({s for s in srcs if s.startswith("J_")} |
                   {d for d in sinks if d.startswith("J_")})
    # config layout
    off, layout = 0, []
    for d, sl in sinks.items():
        w = (len(sl) - 1).bit_length()
        layout.append((d, sl, w, off))
        off += w
    total = off
    o = []
    o.append("// GENERATED by design/gen/gen_switch_matrix.py from")
    o.append("// design/fabulous/Tile/LOGIC4/LOGIC4_switch_matrix.list -- DO NOT EDIT.")
    o.append("// Regenerate: python3 design/gen/gen_switch_matrix.py \\")
    o.append("//   design/fabulous/Tile/LOGIC4/LOGIC4_switch_matrix.list \\")
    o.append("//   design/rtl/logic_tile_switch_matrix.v")
    o.append("//")
    o.append("// Combinational LOGIC4 switch matrix: %d sinks, %d config bits." % (len(sinks), total))
    o.append("// Per-sink select field position/width/sources are listed below; a")
    o.append("// select value >= fan-in drives 0.  No timing is claimed.")
    o.append("")
    o.append("`default_nettype none")
    o.append("`timescale 1ns/1ps")
    o.append("")
    o.append("module logic_tile_switch_matrix (")
    o.append("    input  wire [%d:0] cfg," % (total - 1))
    ps = ["    input  wire %s" % s for s in ports_in] + ["    output wire %s" % d for d in ports_out]
    o.append(",\n".join(ps))
    o.append(");")
    o.append("")
    for j in jumps:
        if "_END" in j:
            o.append("    wire %s;" % j)
        else:
            o.append("    wire %s;" % j)
    for j in jumps:
        if "_BEG" in j:
            o.append("    assign %s = %s;" % (j.replace("BEG", "END"), j))
    o.append("")
    for d, sl, w, of in layout:
        o.append("    // %s: fan-in %d, cfg[%s]" % (
            d, len(sl), ("%d:%d" % (of + w - 1, of)) if w > 1 else (str(of) if w else "none")))
        if w == 0:
            o.append("    assign %s = %s;" % (d, sl[0]))
        else:
            o.append("    reg %s_r;" % d)
            o.append("    always @* begin")
            o.append("        case (cfg[%d:%d])" % (of + w - 1, of))
            for i, s in enumerate(sl):
                o.append("            %d'd%d: %s_r = %s;" % (w, i, d, s))
            o.append("            default: %s_r = 1'b0;" % d)
            o.append("        endcase")
            o.append("    end")
            o.append("    assign %s = %s_r;" % (d, d))
    o.append("")
    o.append("endmodule")
    o.append("")
    o.append("`default_nettype wire")
    open(out, "w").write("\n".join(o) + "\n")
    # testbench include
    t = ["// GENERATED by design/gen/gen_switch_matrix.py -- DO NOT EDIT.",
         "// Table covers every sink that is a tile port with port-only sources;",
         "// jump-wire paths (J_*_BEG -> *_EN/*_SR) are checked by hand in the tb.",
         "localparam NSRC = %d;" % len(ports_in),
         "localparam NSNK = %d;" % len(ports_out),
         "localparam CFGW = %d;" % total,
         "localparam NROW = %d;" % sum(1 for d, sl, w, of in layout if d in ports_out and all(x in ports_in for x in sl)),
         "localparam MAXFAN = %d;" % max(len(sl) for sl in sinks.values()),
         "wire [NSRC-1:0] src;", "wire [NSNK-1:0] snk;",
         "logic_tile_switch_matrix dut (", "    .cfg(cfg),"]
    conns = ["    .%s(src[%d])" % (s_, i) for i, s_ in enumerate(ports_in)] + \
            ["    .%s(snk[%d])" % (d_, i) for i, d_ in enumerate(ports_out)]
    t.append(",\n".join(conns))
    t.append(");")
    t.append("integer tbl_snk [0:NROW-1]; integer tbl_off [0:NROW-1];")
    t.append("integer tbl_w [0:NROW-1]; integer tbl_n [0:NROW-1];")
    t.append("integer tbl_src [0:NROW*MAXFAN-1];")
    t.append("task load_table; begin")
    r = 0
    for d, sl, w, of in layout:
        if d in ports_out and all(x in ports_in for x in sl):
            t.append("  tbl_snk[%d]=%d; tbl_off[%d]=%d; tbl_w[%d]=%d; tbl_n[%d]=%d;" % (
                r, ports_out.index(d), r, of, r, w, r, len(sl)))
            for i, x in enumerate(sl):
                t.append("  tbl_src[%d]=%d;" % (r * max(len(q) for q in sinks.values()) + i, ports_in.index(x)))
            r += 1
    t.append("end endtask")
    open(tbinc, "w").write("\n".join(t) + "\n")
    # stats on stdout
    from collections import Counter
    c = Counter(len(sl) for sl in sinks.values())
    print("sinks=%d cfg_bits=%d fanin_hist=%s" % (len(sinks), total, dict(sorted(c.items()))))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
